// 确定性的价格浮动因子（0.85–1.20），保证每次加载结果一致
function variation(marketIdx, commodityIdx, dayIdx) {
  const h = (marketIdx * 73 + commodityIdx * 151 + dayIdx * 37) % 100;
  return 0.85 + h / 100 * 0.35;
}

function buildRecords() {
  const records = [];
  const dayCount = 2; // 最近两天
  MARKETS.forEach((m, mi) => {
    COMMODITY_BASE.forEach((c, ci) => {
      for (let di = 0; di < dayCount; di++) {
        const f = variation(mi, ci, di);
        const modal = Math.round(c.base * f * 100) / 100;
        const min = Math.round(modal * 0.88 * 100) / 100;
        const max = Math.round(modal * 1.12 * 100) / 100;
        const d = new Date(Date.now() - di * 86400000);
        records.push({
          commodity: c.name,
          market: m.market,
          province: m.province,
          city: m.city,
          modal_price: modal,
          min_price: min,
          max_price: max,
          arrival_date: d.toISOString().slice(0, 10),
        });
      }
    });
  });
  return records;
}

