// 把种子条目展开成完整知识条目
function buildCrop(seed, id) {
  const tpl = CATEGORY_TEMPLATES[seed.c] || CATEGORY_TEMPLATES["粮食"];
  return {
    id,
    name: seed.n,
    aliases: seed.a || [],
    category: seed.c,
    season: seed.s,
    soil: (seed.soil || "").split("|").filter(Boolean),
    climate: seed.cli || "",
    water: seed.w || "",
    duration: seed.d || "",
    sowing_time: seed.st || "",
    fertilizer: seed.f || "",
    irrigation: seed.irr || "",
    yield_info: seed.y || "",
    description: seed.desc || "",
    steps: [...(seed.hi || []), ...tpl.steps],
    common_mistakes: seed.m || tpl.mistakes,
  };
}

export const CROP_KNOWLEDGE = [
  ...DETAILED_CROPS,
  ...EXTRA_SEEDS.map((s, i) => buildCrop(s, 100 + i)),
];

// 本地搜索：按名称、别名、类别和简介匹配；query 为空时返回全部
export function searchLocalCrops(query) {
  const q = (query || "").trim().toLowerCase();
  if (!q) return CROP_KNOWLEDGE;
  return CROP_KNOWLEDGE.filter((crop) => {
    const haystacks = [
      crop.name,
      ...(crop.aliases || []),
      crop.description || "",
      crop.category || "",
    ];
    return haystacks.some((t) => t.toLowerCase().includes(q));
  });
}
