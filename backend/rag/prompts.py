def get_season_info():
    """Return (formatted_date, season_name) based on current month (中国农时)."""
    from datetime import datetime
    now = datetime.now()
    month = now.month
    date_str = now.strftime("%Y年%m月%d日")

    # 中国农时（按公历月份大致划分，南北略有差异）
    if month in (2, 3, 4):
        season = "春耕备耕 —— 春播作物（水稻育秧、春玉米、春大豆、马铃薯等）准备与播种，冬小麦返青管理"
    elif month in (5, 6, 7):
        season = "夏管与夏收夏种 —— 冬小麦收获、夏播（夏玉米、夏大豆、水稻插秧）、大田管理"
    elif month in (8, 9, 10):
        season = "秋收秋种 —— 春玉米、水稻、大豆、花生等收获，冬小麦、油菜播种"
    else:                             # Nov-Jan
        season = "冬季农闲与越冬管理 —— 冬小麦越冬管理、大棚蔬菜生产、农田水利与农资准备"

    return date_str, season


